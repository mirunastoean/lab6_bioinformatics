import random

def get_reverse_complement(seq):
    complement = {'A': 'T', 'T': 'A', 'C': 'G', 'G': 'C'}
    return ''.join(complement[base] for base in reversed(seq))

random.seed(42)
host_dna = ''.join(random.choices('ATCG', k=300))

dr1 = "TACATG"
ir1 = "GGCCAA"
te1_body = "ATGCGTAC"
te1_full = dr1 + ir1 + te1_body + get_reverse_complement(ir1) + dr1

ir2 = "CCGGTA"
te2_body = "TTAAGGCC"
te2_full = ir2 + te2_body + get_reverse_complement(ir2)

dr3 = "GGTTAA"
te3_body = "CCCTTTGGG"
te3_full = dr3 + te3_body + dr3

dna_sequence = host_dna[:50] + te1_full + host_dna[50:150] + te2_full + host_dna[150:250] + te3_full + host_dna[250:]

print("Generated DNA Sequence (Length: {}):".format(len(dna_sequence)))
print(dna_sequence)
print("-" * 50)

def detect_transposons(sequence, min_repeat_len=6, max_spacer_len=15):
    found_elements = []
    seq_len = len(sequence)

    for i in range(seq_len - min_repeat_len):
        motif = sequence[i:i+min_repeat_len]

        search_start = i + min_repeat_len
        search_end = search_start + max_spacer_len + min_repeat_len

        if search_end > seq_len:
            search_end = seq_len

        window = sequence[search_start:search_end]

        if motif in window:
            match_idx = window.find(motif) + search_start
            te_end = match_idx + min_repeat_len

            inner_start = i + min_repeat_len
            inner_end = match_idx
            inner_seq = sequence[inner_start:inner_end]

            if len(inner_seq) >= min_repeat_len * 2:
                potential_ir = inner_seq[:min_repeat_len]
                if inner_seq[-min_repeat_len:] == get_reverse_complement(potential_ir):
                    found_elements.append({
                        "type": "Case 1: Direct Repeats + Inverted Repeats",
                        "start": i, "end": te_end, "sequence": sequence[i:te_end]
                    })
                    continue

            found_elements.append({
                "type": "Case 3: Direct Repeats Only",
                "start": i, "end": te_end, "sequence": sequence[i:te_end]
            })

        rev_comp_motif = get_reverse_complement(motif)
        if rev_comp_motif in window:
            match_idx = window.find(rev_comp_motif) + search_start
            te_end = match_idx + min_repeat_len

            is_nested = False
            for elem in found_elements:
                if i >= elem["start"] and te_end <= elem["end"]:
                    is_nested = True
                    break

            if not is_nested:
                found_elements.append({
                    "type": "Case 2: Inverted Repeats Only",
                    "start": i, "end": te_end, "sequence": sequence[i:te_end]
                })

    return found_elements

print("Detecting Transposable Elements...\n")
detected_tes = detect_transposons(dna_sequence, min_repeat_len=6, max_spacer_len=20)

filtered_tes = []
for te in detected_tes:
    if not any(te['start'] >= other['start'] and te['end'] <= other['end'] and te != other for other in detected_tes):
        if te not in filtered_tes:
            filtered_tes.append(te)

for idx, te in enumerate(filtered_tes, 1):
    print(f"Element {idx}: {te['type']}")
    print(f"Position: Start {te['start']} | End {te['end']}")
    print(f"Sequence: {te['sequence']}\n")